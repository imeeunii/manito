CREATE TABLE IF NOT EXISTS classes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  student_count INTEGER NOT NULL,
  excluded_numbers TEXT NOT NULL DEFAULT '[]',
  assignments TEXT NOT NULL,
  custom_missions TEXT NOT NULL DEFAULT '{}',
  teacher_pin_hash TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS student_entries (
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  student_number INTEGER NOT NULL,
  viewed_at TIMESTAMPTZ,
  received_viewed_at TIMESTAMPTZ,
  strength_one TEXT NOT NULL DEFAULT '',
  strength_two TEXT NOT NULL DEFAULT '',
  strength_three TEXT NOT NULL DEFAULT '',
  poem_name TEXT NOT NULL DEFAULT '',
  poem_line_one TEXT NOT NULL DEFAULT '',
  poem_line_two TEXT NOT NULL DEFAULT '',
  poem_line_three TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (class_id, student_number)
);

